#!/usr/bin/env node
/**
 * Generate index.ts that imports and re-exports generated tokens
 * Run AFTER Style Dictionary build
 */

const fs = require('fs');
const path = require('path');

const tokensPath = path.join(__dirname, '../../../packages/@dsai/tokens/dist/ts/tokens.ts');
const outputPath = path.join(__dirname, '../../../packages/@dsai/tokens/src/index.ts');

// Read the generated tokens file
if (!fs.existsSync(tokensPath)) {
  console.error('❌ Tokens file not found. Run Style Dictionary build first.');
  process.exit(1);
}

const tokensContent = fs.readFileSync(tokensPath, 'utf-8');

// Extract all exported token names
const exportRegex = /export const (\w+) = /g;
const tokenNames = [];
let match;
while ((match = exportRegex.exec(tokensContent)) !== null) {
  tokenNames.push(match[1]);
}

console.log(`📦 Found ${tokenNames.length} tokens`);

// Generate grouped structure
const output = `/**
 * DSAi Design Tokens
 * Auto-generated from Style Dictionary output
 * DO NOT EDIT - this file is generated by tools/scripts/tokens/generate-token-index.cjs
 */

// Re-export all tokens for direct access
export * from '../dist/ts/tokens.js';

// Import all tokens dynamically for grouping
import * as allTokensImport from '../dist/ts/tokens.js';

// Type for token with value property (Storybook compatibility)
interface TokenValue {
  value: string;
}

// Group tokens by category
const color: Record<string, Record<string, TokenValue>> = {};
const theme: Record<string, TokenValue> = {};
const component: { semantic: Record<string, TokenValue> } = { semantic: {} };
const neutral: Record<string, TokenValue> = {};
const background: Record<string, TokenValue> = {};
const opacity: Record<string, TokenValue> = {};
const border: { color: Record<string, TokenValue>; width: Record<string, TokenValue> } = {
  color: {},
  width: {},
};

// Parse token names into nested structure
const allTokens = allTokensImport as Record<string, string>;

Object.entries(allTokens).forEach(([key, value]) => {
  const token: TokenValue = { value };

  if (key.startsWith('color')) {
    // colorBlue50 -> color.blue['50']
    const match = key.match(/^color([A-Z][a-z]+)(\\d+)$/);
    if (match) {
      const hue = match[1].toLowerCase();
      const step = match[2];
      if (!color[hue]) color[hue] = {};
      color[hue][step] = token;
    }
  } else if (key.startsWith('theme')) {
    // themePrimary -> theme.primary
    const name = key.replace('theme', '');
    const kebab = name.charAt(0).toLowerCase() + name.slice(1).replace(/([A-Z])/g, '-$1').toLowerCase();
    theme[kebab] = token;
  } else if (key.startsWith('componentSemantic')) {
    // componentSemanticWarningBgSubtle -> component.semantic['warning-bg-subtle']
    const name = key.replace('componentSemantic', '');
    const kebab = name.charAt(0).toLowerCase() + name.slice(1).replace(/([A-Z])/g, '-$1').toLowerCase();
    component.semantic[kebab] = token;
  } else if (key.startsWith('neutral')) {
    // neutralWhite -> neutral.white
    const name = key.replace('neutral', '');
    const kebab = name.charAt(0).toLowerCase() + name.slice(1).replace(/([A-Z])/g, '-$1').toLowerCase();
    neutral[kebab] = token;
  } else if (key.startsWith('background')) {
    // backgroundPrimary -> background.primary
    const name = key.replace('background', '');
    const kebab = name.charAt(0).toLowerCase() + name.slice(1).replace(/([A-Z])/g, '-$1').toLowerCase();
    background[kebab] = token;
  } else if (key.startsWith('opacity')) {
    // opacity50 -> opacity['50']
    const num = key.replace('opacity', '');
    opacity[num] = token;
  } else if (key.startsWith('borderColor')) {
    // borderColorDefault -> border.color.default
    const name = key.replace('borderColor', '');
    const kebab = name.charAt(0).toLowerCase() + name.slice(1).replace(/([A-Z])/g, '-$1').toLowerCase();
    border.color[kebab] = token;
  } else if (key.startsWith('borderWidth')) {
    // borderWidthThin -> border.width.thin
    const name = key.replace('borderWidth', '');
    const kebab = name.charAt(0).toLowerCase() + name.slice(1).replace(/([A-Z])/g, '-$1').toLowerCase();
    border.width[kebab] = token;
  }
});

// Export grouped tokens (compatible with Storybook stories)
export const tokens = {
  color,
  theme,
  component,
  neutral,
  background,
  opacity,
  border,
};

export default tokens;
`;

fs.writeFileSync(outputPath, output);
console.log(`✅ Generated ${outputPath} with ${tokenNames.length} tokens`);

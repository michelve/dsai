#!/usr/bin/env node

/**
 * Generate Figma Code Connect for Icon Components
 *
 * Creates a comprehensive Icon.figma.tsx file that maps all Bootstrap Icons
 * to their React components for Figma Code Connect.
 *
 * Usage:
 *   node tools/scripts/icons/generate-figma-code-connect.cjs
 *
 * This script:
 * 1. Reads all generated icon components from the components directory
 * 2. Generates a single Icon.figma.tsx file with all icon mappings
 * 3. Uses the variant pattern to map Figma icon names to React components
 *
 * @packageDocumentation
 */

const fs = require('node:fs');
const path = require('node:path');

// Paths
const COMPONENTS_DIR = path.join(
  __dirname,
  '../../../packages/@dsai-io/react/src/components/Icon/components'
);
const OUTPUT_FILE = path.join(
  __dirname,
  '../../../packages/@dsai-io/react/src/components/Icon/Icon.figma.tsx'
);

/**
 * Convert PascalCase component name to kebab-case icon name
 * e.g., "CheckCircleIcon" -> "check-circle"
 */
function toKebabCase(componentName) {
  // Remove "Icon" suffix
  const baseName = componentName.replace(/Icon$/, '');

  // Handle special cases with numbers at start (Icon0Circle -> 0-circle)
  if (baseName.startsWith('Icon') && /^\d/.test(baseName.charAt(4))) {
    const withoutPrefix = baseName.slice(4);
    return withoutPrefix
      .replaceAll(/([A-Z])/g, '-$1')
      .toLowerCase()
      .replace(/^-/, '');
  }

  // Convert PascalCase to kebab-case
  return baseName
    .replaceAll(/([A-Z])/g, '-$1')
    .toLowerCase()
    .replace(/^-/, '')
    .replaceAll('--', '-'); // Handle consecutive capitals
}

/**
 * Get all icon component names from the components directory
 */
function getIconComponents() {
  const files = fs
    .readdirSync(COMPONENTS_DIR)
    .filter((f) => f.endsWith('.tsx') && f !== 'index.ts');

  return files.map((file) => {
    const componentName = file.replace('.tsx', '');
    const iconName = toKebabCase(componentName);
    return {
      componentName,
      iconName,
    };
  });
}

/**
 * Generate the Figma Code Connect file content
 */
function generateFigmaCodeConnect(icons) {
  // Group icons for imports (we'll import all of them)
  const imports = icons.map((icon) => icon.componentName).join(',\n  ');

  // Generate the figma.connect calls for each icon
  const connections = icons
    .map(
      (icon) => `
figma.connect(${icon.componentName}, FIGMA_URLS.icon, {
  variant: { Name: '${icon.iconName}' },
  props: {
    size: figma.enum('Size', {
      '12': 12,
      '16': 16,
      '20': 20,
      '24': 24,
      '32': 32,
      '48': 48,
    }),
    color: figma.string('Color'),
    'aria-label': figma.string('Aria Label'),
  },
  example: (props) => (
    <${icon.componentName}
      size={props.size}
      color={props.color}
      aria-label={props['aria-label']}
    />
  ),
});`
    )
    .join('\n');

  return `/**
 * Figma Code Connect - Icon Components
 *
 * AUTO-GENERATED FILE - DO NOT EDIT MANUALLY
 * Generated by: tools/scripts/icons/generate-figma-code-connect.js
 *
 * Maps all Bootstrap Icon React components to Figma.
 * Total icons: ${icons.length}
 *
 * @see https://help.figma.com/hc/en-us/articles/23920389749655-Code-Connect
 */

import figma from '@figma/code-connect';
import {
  ${imports},
} from './components';

// =============================================================================
// FIGMA URL CONFIGURATION
// =============================================================================

/**
 * Figma component URLs - Replace with actual Figma URLs
 * Format: https://www.figma.com/design/<file-key>?node-id=<node-id>
 */
const FIGMA_URLS = {
  icon: '<FIGMA_DSAI_ICON>',
} as const;

// =============================================================================
// ICON MAPPINGS (${icons.length} icons)
// =============================================================================
${connections}

// =============================================================================
// USAGE EXAMPLES
// =============================================================================

/**
 * Icon Usage Patterns
 *
 * Decorative icons (inside buttons, next to text):
 * \`\`\`tsx
 * <Button startIcon={<CheckIcon />}>Save</Button>
 * <span><InfoCircleIcon /> Help text</span>
 * \`\`\`
 *
 * Semantic icons (standalone, convey meaning):
 * \`\`\`tsx
 * <CheckCircleIcon aria-label="Success" />
 * <ExclamationTriangleIcon aria-label="Warning" />
 * \`\`\`
 *
 * With tooltip:
 * \`\`\`tsx
 * <InfoCircleIcon title="More information" />
 * \`\`\`
 *
 * Custom size and color:
 * \`\`\`tsx
 * <SearchIcon size={24} color="var(--bs-primary)" />
 * \`\`\`
 */
`;
}

/**
 * Main function
 */
async function main() {
  console.log('🎨 Generating Figma Code Connect for Icon components...\n');

  // Check if components directory exists
  if (!fs.existsSync(COMPONENTS_DIR)) {
    console.error('❌ Components directory not found. Run generate-icons.js first.');
    process.exit(1);
  }

  // Get all icon components
  const icons = getIconComponents();
  console.log(`📁 Found ${icons.length} icon components\n`);

  // Generate the Figma Code Connect file
  const content = generateFigmaCodeConnect(icons);

  // Write the file
  fs.writeFileSync(OUTPUT_FILE, content);

  console.log(`✅ Generated Icon.figma.tsx with ${icons.length} icon mappings`);
  console.log(`📄 Output: ${OUTPUT_FILE}\n`);

  // Print some stats
  const sampleIcons = icons.slice(0, 5).map((i) => `  - ${i.componentName} → "${i.iconName}"`);
  console.log('Sample mappings:');
  console.log(sampleIcons.join('\n'));
  console.log(`  ... and ${icons.length - 5} more\n`);
}

main().catch(console.error);
